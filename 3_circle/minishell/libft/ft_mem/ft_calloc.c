#include "libft.h"

void	*ft_calloc(size_t count, size_t size)
{
	char	*space;
	size_t	i;

	i = 0;
	space = malloc(size * count + 1);
	if (!space)
		return (NULL);
	while (i < count * size + 1)
		space[i++] = '\0';
	return (space);
}
